"""Minimal, provider-neutral Media Foundry planning worker.

This service validates and persists plans only. It never downloads model weights, executes
shell commands, or claims to render media. GPU/provider adapters run in separate workers.
"""
from __future__ import annotations

import hmac
import json
import os
import secrets
import tempfile
import uuid
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from typing import Any, Mapping

from director import MediaPlanError, build_production_plan, write_plan

MAX_BODY_BYTES = 1_048_576


def worker_ready(spool_dir: str | Path, token: str | None) -> tuple[bool, str]:
    if not token:
        return False, "worker_auth_not_configured"
    if len(token) < 32:
        return False, "worker_auth_token_too_short"
    try:
        root = Path(spool_dir)
        root.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(dir=root, prefix=".ready-", delete=True):
            pass
    except OSError:
        return False, "spool_directory_not_writable"
    return True, "ready"


def persist_plan(request: Mapping[str, Any], spool_dir: str | Path) -> dict[str, Any]:
    """Persist a validated plan beneath the configured spool root."""
    plan = build_production_plan(request)
    root = Path(spool_dir).resolve()
    destination = root / plan.job_id / "plan.json"
    # job_id is generated by the service, never accepted from the incoming request.
    write_plan(plan, destination)
    return {"job_id": plan.job_id, "status": "planned_not_rendered",
            "plan_path": str(destination.relative_to(root)),
            "total_duration_sec": plan.total_duration_sec}


class Handler(BaseHTTPRequestHandler):
    server_version = "DreamCoMediaWorker/0.1"

    def _send(self, status: int, payload: Mapping[str, Any]) -> None:
        body = json.dumps(dict(payload), separators=(",", ":")).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self) -> None:
        if self.path == "/healthz":
            self._send(200, {"status": "alive", "service": "dreamco-media-planner"})
            return
        if self.path == "/readyz":
            ready, reason = worker_ready(self.server.spool_dir, self.server.worker_token)
            self._send(200 if ready else 503, {"status": "ready" if ready else "not_ready",
                                                "reason": reason})
            return
        self._send(404, {"error": "not_found"})

    def do_POST(self) -> None:
        if self.path != "/v1/jobs/plan":
            self._send(404, {"error": "not_found"})
            return
        expected = self.server.worker_token
        if not expected:
            self._send(503, {"error": "worker_auth_not_configured"})
            return
        supplied = self.headers.get("Authorization", "")
        prefix = "Bearer "
        if not supplied.startswith(prefix) or not hmac.compare_digest(supplied[len(prefix):], expected):
            self._send(401, {"error": "unauthorized"})
            return
        try:
            length = int(self.headers.get("Content-Length", "0"))
        except ValueError:
            self._send(400, {"error": "invalid_content_length"})
            return
        if length <= 0:
            self._send(400, {"error": "empty_body"})
            return
        if length > MAX_BODY_BYTES:
            self._send(413, {"error": "request_too_large"})
            return
        try:
            raw = self.rfile.read(length)
            payload = json.loads(raw)
            if not isinstance(payload, dict):
                raise ValueError("JSON body must be an object")
            result = persist_plan(payload, self.server.spool_dir)
        except (json.JSONDecodeError, UnicodeDecodeError, ValueError, MediaPlanError) as exc:
            self._send(400, {"error": "invalid_production_request", "detail": str(exc)})
            return
        except OSError:
            self._send(500, {"error": "plan_persistence_failed"})
            return
        self._send(201, result)

    def log_message(self, fmt: str, *args: Any) -> None:
        # Avoid logging request bodies, authorization headers, or user prompts.
        super().log_message(fmt, *args)


class MediaWorkerServer(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True

    def __init__(self, address: tuple[str, int], spool_dir: str, worker_token: str | None):
        self.spool_dir = spool_dir
        self.worker_token = worker_token
        super().__init__(address, Handler)


def main() -> None:
    host = os.environ.get("DREAMCO_WORKER_HOST", "127.0.0.1")
    port = int(os.environ.get("DREAMCO_WORKER_PORT", "8080"))
    spool = os.environ.get("DREAMCO_MEDIA_SPOOL", "/var/lib/dreamco-media")
    token = os.environ.get("DREAMCO_WORKER_TOKEN")
    ready, reason = worker_ready(spool, token)
    if not ready:
        raise SystemExit(f"worker configuration invalid: {reason}")
    server = MediaWorkerServer((host, port), spool, token)
    print(f"DreamCo Media planning worker listening on {host}:{port}")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
